-- The Java repository also creates this table automatically on first startup.
-- Run this script in Supabase Dashboard > SQL Editor if you want to create it manually.
create table if not exists public.reports (
    id integer generated by default as identity primary key,
    type text not null check (type in ('LOST', 'FOUND')),
    title text not null,
    description text not null,
    category text not null,
    location text not null,
    report_date date not null,
    reporter_name text not null,
    reporter_campus_id text not null,
    reporter_contact text not null,
    status text not null check (status in ('OPEN', 'CLAIMED', 'RETURNED')),
    claimed_by text not null default ''
);

create index if not exists idx_reports_status_type on public.reports(status, type);

alter table public.reports enable row level security;

-- Public report cards may show item details and the poster's display name, but must
-- never expose campus IDs, phone numbers, email addresses, or claimant IDs.
revoke all on table public.reports from public, anon, authenticated;
grant select (id, type, title, description, category, location, report_date, reporter_name, status)
    on public.reports to anon, authenticated;
grant insert (type, title, description, category, location, report_date, reporter_name,
              reporter_campus_id, reporter_contact, status, claimed_by)
    on public.reports to anon, authenticated;
grant update (status, claimed_by) on public.reports to anon, authenticated;
grant usage, select on sequence public.reports_id_seq to anon, authenticated;

drop policy if exists "Public can read report cards" on public.reports;
create policy "Public can read report cards" on public.reports
    for select to anon, authenticated using (true);

drop policy if exists "Public can post open reports" on public.reports;
create policy "Public can post open reports" on public.reports
    for insert to anon, authenticated with check (status = 'OPEN' and claimed_by = '');

drop policy if exists "Public can claim open reports" on public.reports;
create policy "Public can claim open reports" on public.reports
    for update to anon, authenticated using (status = 'OPEN') with check (status = 'CLAIMED');

drop policy if exists "Public can complete claimed reports" on public.reports;
create policy "Public can complete claimed reports" on public.reports
    for update to anon, authenticated using (status = 'CLAIMED') with check (status = 'RETURNED');

