package edu.campus.lostfound;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Base64;
import java.util.List;

/** Persists reports in the project's hosted Supabase PostgreSQL database. */
public class ReportRepository {
    private static final Path LEGACY_FILE = Path.of("data", "reports.tsv");
    private final String jdbcUrl = System.getenv("SUPABASE_JDBC_URL");
    private final String username = setting("SUPABASE_DB_USER", "postgres");
    private final String password = System.getenv("SUPABASE_DB_PASSWORD");

    private static String setting(String name, String fallback) {
        String value = System.getenv(name);
        return value == null || value.isBlank() ? fallback : value;
    }

    private Connection connect() throws SQLException {
        if (jdbcUrl == null || jdbcUrl.isBlank() || password == null || password.isBlank()) {
            throw new SQLException("Supabase is not configured. Set SUPABASE_JDBC_URL and SUPABASE_DB_PASSWORD in the environment.");
        }
        Connection connection = DriverManager.getConnection(jdbcUrl, username, password);
        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS public.reports (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        type TEXT NOT NULL CHECK (type IN ('LOST', 'FOUND')),
                        title TEXT NOT NULL,
                        description TEXT NOT NULL,
                        category TEXT NOT NULL,
                        location TEXT NOT NULL,
                        report_date DATE NOT NULL,
                        reporter_name TEXT NOT NULL,
                        reporter_campus_id TEXT NOT NULL,
                        reporter_contact TEXT NOT NULL,
                        status TEXT NOT NULL CHECK (status IN ('OPEN', 'CLAIMED', 'RETURNED')),
                        claimed_by TEXT NOT NULL DEFAULT ''
                    )
                    """);
            statement.execute("CREATE INDEX IF NOT EXISTS idx_reports_status_type ON public.reports(status, type)");
        } catch (SQLException ex) {
            connection.close();
            throw ex;
        }
        return connection;
    }

    public List<ItemReport> load(LostAndFoundService service) throws IOException {
        List<ItemReport> loaded = new ArrayList<>();
        if (isEmpty() && Files.exists(LEGACY_FILE)) {
            List<ItemReport> migrated = loadLegacyTsv(service, LEGACY_FILE);
            if (!migrated.isEmpty()) {
                save(migrated);
                return migrated;
            }
        }
        try (Connection connection = connect();
             Statement statement = connection.createStatement();
             ResultSet rows = statement.executeQuery("SELECT * FROM public.reports ORDER BY id")) {
            while (rows.next()) {
                User reporter = new User(rows.getString("reporter_name"),
                        rows.getString("reporter_campus_id"), rows.getString("reporter_contact"));
                loaded.add(service.restore(rows.getInt("id"), ReportType.valueOf(rows.getString("type")),
                        rows.getString("title"), rows.getString("description"), rows.getString("category"),
                        rows.getString("location"), reporter, rows.getDate("report_date").toLocalDate(),
                        ItemStatus.valueOf(rows.getString("status")), rows.getString("claimed_by")));
            }
            return loaded;
        } catch (SQLException | RuntimeException ex) {
            throw new IOException("Could not load reports from Supabase PostgreSQL.", ex);
        }
    }

    private boolean isEmpty() throws IOException {
        try (Connection connection = connect();
             Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery("SELECT COUNT(*) FROM public.reports")) {
            return result.next() && result.getInt(1) == 0;
        } catch (SQLException ex) {
            throw new IOException("Could not inspect Supabase reports table.", ex);
        }
    }

    private List<ItemReport> loadLegacyTsv(LostAndFoundService service, Path legacyFile) throws IOException {
        List<ItemReport> migrated = new ArrayList<>();
        List<String> lines = Files.readAllLines(legacyFile);
        if (lines.isEmpty() || !"CAMPUS_LOST_FOUND_V1".equals(lines.get(0))) return migrated;
        for (int lineNumber = 1; lineNumber < lines.size(); lineNumber++) {
            String line = lines.get(lineNumber);
            if (line.isBlank()) continue;
            try {
                String[] f = line.split("\\t", -1);
                if (f.length != 12) throw new IllegalArgumentException("Expected 12 fields");
                User reporter = new User(decode(f[7]), decode(f[8]), decode(f[9]));
                migrated.add(service.restore(Integer.parseInt(f[0]), ReportType.valueOf(f[1]),
                        decode(f[2]), decode(f[3]), decode(f[4]), decode(f[5]), reporter,
                        LocalDate.parse(f[6]), ItemStatus.valueOf(f[10]), decode(f[11])));
            } catch (RuntimeException ex) {
                throw new IOException("Could not migrate legacy report at line " + (lineNumber + 1), ex);
            }
        }
        return migrated;
    }

    private static String decode(String encoded) {
        if (encoded.isEmpty()) return "";
        return new String(Base64.getUrlDecoder().decode(encoded), java.nio.charset.StandardCharsets.UTF_8);
    }

    /** Replaces the stored report snapshot inside one PostgreSQL transaction. */
    public void save(List<ItemReport> reports) throws IOException {
        String insert = """
                INSERT INTO public.reports(id, type, title, description, category, location, report_date,
                                           reporter_name, reporter_campus_id, reporter_contact, status, claimed_by)
                VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """;
        try (Connection connection = connect()) {
            connection.setAutoCommit(false);
            try (Statement delete = connection.createStatement();
                 PreparedStatement statement = connection.prepareStatement(insert)) {
                delete.executeUpdate("DELETE FROM public.reports");
                for (ItemReport report : reports) {
                    statement.setInt(1, report.getId());
                    statement.setString(2, report.getType().name());
                    statement.setString(3, report.getTitle());
                    statement.setString(4, report.getDescription());
                    statement.setString(5, report.getCategory());
                    statement.setString(6, report.getLocation());
                    statement.setObject(7, report.getReportDate());
                    statement.setString(8, report.getReporter().getName());
                    statement.setString(9, report.getReporter().getCampusId());
                    statement.setString(10, report.getReporter().getContact());
                    statement.setString(11, report.getStatus().name());
                    statement.setString(12, report.getClaimedBy() == null ? "" : report.getClaimedBy());
                    statement.addBatch();
                }
                statement.executeBatch();
                try (Statement sequence = connection.createStatement()) {
                    sequence.execute("SELECT setval(pg_get_serial_sequence('public.reports', 'id'), "
                            + "COALESCE((SELECT MAX(id) FROM public.reports), 1), "
                            + "EXISTS (SELECT 1 FROM public.reports))");
                }
                connection.commit();
            } catch (SQLException ex) {
                connection.rollback();
                throw ex;
            }
        } catch (SQLException | RuntimeException ex) {
            throw new IOException("Could not save reports to Supabase PostgreSQL.", ex);
        }
    }
}
